<?php

namespace Whitebit\SpotTrading\Types;

use Whitebit\Core\Json\JsonSerializableType;
use Whitebit\Core\Json\JsonProperty;

class GetDelistingOrderHistoryResponseItem extends JsonSerializableType
{
    /**
     * @var ?int $id Unique order identifier assigned by the matching engine.
     */
    #[JsonProperty('id')]
    public ?int $id;

    /**
     * @var ?string $clientOrderId Custom client order identifier. Reverse close orders carry the platform-generated value prefixed with `delisting-`. Returns an empty string when the original order had no client identifier.
     */
    #[JsonProperty('clientOrderId')]
    public ?string $clientOrderId;

    /**
     * @var ?float $createdAt Unix timestamp in seconds (UTC) of order creation, with microsecond precision.
     */
    #[JsonProperty('createdAt')]
    public ?float $createdAt;

    /**
     * @var ?float $finishAt Unix timestamp in seconds (UTC) at which the order reached its final status, with microsecond precision. Primary sort key, descending.
     */
    #[JsonProperty('finishAt')]
    public ?float $finishAt;

    /**
     * @var ?string $market Trading pair the order belongs to. Format: `BASE_QUOTE`.
     */
    #[JsonProperty('market')]
    public ?string $market;

    /**
     * @var ?value-of<GetDelistingOrderHistoryResponseItemSide> $side Order side. Possible values: `buy`, `sell`.
     */
    #[JsonProperty('side')]
    public ?string $side;

    /**
     * @var ?string $type Order type. Possible values: `limit`, `market`, `stock market`, `stop limit`, `stop market`.
     */
    #[JsonProperty('type')]
    public ?string $type;

    /**
     * @var ?string $price Limit price per unit in quote currency. Returns `"0"` for market orders.
     */
    #[JsonProperty('price')]
    public ?string $price;

    /**
     * @var ?string $amount Order quantity in base currency for limit orders, or in quote currency for buy market orders.
     */
    #[JsonProperty('amount')]
    public ?string $amount;

    /**
     * @var ?string $dealStock Filled amount in base (stock) currency.
     */
    #[JsonProperty('dealStock')]
    public ?string $dealStock;

    /**
     * @var ?string $dealMoney Filled amount in quote (money) currency.
     */
    #[JsonProperty('dealMoney')]
    public ?string $dealMoney;

    /**
     * @var ?string $fee Cumulative trading fee charged for filled portions, denominated in the fee asset.
     */
    #[JsonProperty('fee')]
    public ?string $fee;

    /**
     * @var ?string $feeAsset Currency ticker of the asset used to pay the trading fee.
     */
    #[JsonProperty('feeAsset')]
    public ?string $feeAsset;

    /**
     * @var ?string $status Execution outcome in lowercase. Reverse close orders that filled return `filled`. Orders canceled during delisting return `canceled`.
     */
    #[JsonProperty('status')]
    public ?string $status;

    /**
     * @var ?value-of<GetDelistingOrderHistoryResponseItemDelistingKind> $delistingKind Delisting category discriminator. `reverse` marks a reverse close order generated by the platform. `canceled` marks an active order canceled at the moment of delisting.
     */
    #[JsonProperty('delistingKind')]
    public ?string $delistingKind;

    /**
     * @param array{
     *   id?: ?int,
     *   clientOrderId?: ?string,
     *   createdAt?: ?float,
     *   finishAt?: ?float,
     *   market?: ?string,
     *   side?: ?value-of<GetDelistingOrderHistoryResponseItemSide>,
     *   type?: ?string,
     *   price?: ?string,
     *   amount?: ?string,
     *   dealStock?: ?string,
     *   dealMoney?: ?string,
     *   fee?: ?string,
     *   feeAsset?: ?string,
     *   status?: ?string,
     *   delistingKind?: ?value-of<GetDelistingOrderHistoryResponseItemDelistingKind>,
     * } $values
     */
    public function __construct(
        array $values = [],
    ) {
        $this->id = $values['id'] ?? null;
        $this->clientOrderId = $values['clientOrderId'] ?? null;
        $this->createdAt = $values['createdAt'] ?? null;
        $this->finishAt = $values['finishAt'] ?? null;
        $this->market = $values['market'] ?? null;
        $this->side = $values['side'] ?? null;
        $this->type = $values['type'] ?? null;
        $this->price = $values['price'] ?? null;
        $this->amount = $values['amount'] ?? null;
        $this->dealStock = $values['dealStock'] ?? null;
        $this->dealMoney = $values['dealMoney'] ?? null;
        $this->fee = $values['fee'] ?? null;
        $this->feeAsset = $values['feeAsset'] ?? null;
        $this->status = $values['status'] ?? null;
        $this->delistingKind = $values['delistingKind'] ?? null;
    }

    /**
     * @return string
     */
    public function __toString(): string
    {
        return $this->toJson();
    }
}
